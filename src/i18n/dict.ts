const DICTS: Record<Locale, Dict> = { de, en, fr, it, nl };

/** Platzhalter {name} ersetzen */
export function fill(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

export function t(locale: Locale): Dict {
  return DICTS[locale] ?? de;
}

/** Sprachcode für Datums- und Zahlformate */
export const LOCALE_TAGS: Record<Locale, string> = { de: "de-CH", en: "en-GB", fr: "fr-CH", it: "it-CH", nl: "nl-NL" };
/** Open Graph (Vorschau in WhatsApp, Facebook) */
export const OG_LOCALES: Record<Locale, string> = { de: "de_CH", en: "en_GB", fr: "fr_CH", it: "it_CH", nl: "nl_NL" };

export function formatDay(day: string, locale: Locale): string {
  const d = new Date(day + "T12:00:00Z");
  return d.toLocaleDateString(LOCALE_TAGS[locale] ?? "de-CH", { weekday: "short", day: "numeric", month: "short", year: "numeric", timeZone: "UTC" });
}
