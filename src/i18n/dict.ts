/**
 * Sprachen der Hotel-Websites und Buchungsstrecke. Jedes Hotel wählt, welche es anbietet (hotels.content.languages);
 * Deutsch ist immer dabei (Ausgangssprache im Editor und für Übersetzungen).
 */
export type Locale = "de" | "en" | "fr" | "it" | "nl";
export const LOCALES: Locale[] = ["de", "en", "fr", "it", "nl"];
export const LOCALE_NAMES: Record<Locale, string> = { de: "Deutsch", en: "English", fr: "Français", it: "Italiano", nl: "Nederlands" };
export function isLocale(s: string): s is Locale {
  return (LOCALES as string[]).includes(s);
}

/** Reihenfolge, in der fehlende Texte ersetzt werden: gewünschte Sprache, dann Englisch, dann Deutsch */
export function fallbackChain(l: Locale): Locale[] {
  return l === "de" ? ["de", "en"] : l === "en" ? ["en", "de"] : [l, "en", "de"];
}

/** Sprachen, die ein Hotel anbietet (Standard: Deutsch und Englisch). Deutsch steht immer zuerst. */
export function hotelLocales(hotel: { content?: { languages?: string[] } | null }): Locale[] {
  const chosen = (hotel.content?.languages ?? ["de", "en"]).filter(isLocale);
  return ["de", ...LOCALES.filter((l) => l !== "de" && chosen.includes(l))];
}

